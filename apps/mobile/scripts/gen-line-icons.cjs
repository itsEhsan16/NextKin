// The package's `exports` map hides package.json, so locate dist/ through the main entry.
const distDir = path.dirname(require.resolve('@untitledui/icons'));
const out = path.join(__dirname, '..', 'src', 'ui', 'Icon', 'lineIcons.generated.ts');

const entries = [...new Set(NAMES)].sort().map((name) => {
  const source = fs.readFileSync(path.join(distDir, `${name}.js`), 'utf8');
  const paths = [...source.matchAll(/createElement\("path",\{([^}]*)\}/g)].map(([, props]) => {
    const d = /d:"([^"]+)"/.exec(props)?.[1];
    if (!d) throw new Error(`${name}: a path without d`);
    return d;
  });
  if (paths.length === 0) throw new Error(`${name}: no paths found`);
  return `  ${name}: [\n${paths.map((d) => `    '${d}',`).join('\n')}\n  ],`;
});

fs.writeFileSync(
  out,
  [
    '// Generated by scripts/gen-line-icons.cjs from @untitledui/icons — do not edit by hand.',
    '',
    'export const LINE_ICON_PATHS = {',
    ...entries,
    '} as const satisfies Record<string, readonly string[]>;',
    '',
  ].join('\n'),
);
console.log(`Wrote ${entries.length} icons to ${path.relative(process.cwd(), out)}`);
