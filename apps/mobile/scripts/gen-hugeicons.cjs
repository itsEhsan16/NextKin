/** Turns one module's `const X = [ ["path", { d: "…", … }], … ];` into data, without running it. */
function parse(name) {
  const src = fs.readFileSync(path.join(esmDir, `${name}Icon.js`), 'utf8');
  const match = /=\s*(\[[\s\S]*\]);/.exec(src);
  if (!match) throw new Error(`cannot parse ${name}`);
  const json = match[1]
    .replace(/([{,]\s*)([A-Za-z_][A-Za-z0-9_]*)\s*:/g, '$1"$2":')
    .replace(/,\s*([\]}])/g, '$1');
  return JSON.parse(json).map(([tag, attrs]) => {
    const kept = {};
    for (const [key, value] of Object.entries(attrs)) {
      if (key === 'key' || key === 'stroke' || key === 'fill') continue;
      kept[key] = value;
    }
    // Hugeicons marks a filled sub-shape with fill="currentColor"; keep that as a flag.
    if (attrs.fill === 'currentColor') kept.solid = true;
    return [tag, kept];
  });
}

const lines = Object.entries(MAP).map(
  ([appName, hugeName]) => `  ${appName}: ${JSON.stringify(parse(hugeName))},`,
);
const out = path.join(__dirname, '..', 'src', 'ui', 'Icon', 'hugeIcons.generated.ts');
fs.writeFileSync(
  out,
  `// Generated by scripts/gen-hugeicons.cjs from Hugeicons free stroke-rounded (MIT) — do not edit.\n\n` +
    `export type HugeIconElement = [tag: string, attrs: Record<string, string | boolean>];\n\n` +
    `export const HUGE_ICONS = {\n${lines.join('\n')}\n} as const satisfies Record<string, readonly HugeIconElement[]>;\n`,
);
console.log(`wrote ${Object.keys(MAP).length} icons to ${out}`);
