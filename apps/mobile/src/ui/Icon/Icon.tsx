import { memo } from 'react';
import type { StyleProp, ViewStyle } from 'react-native';
import Svg, { Circle, Path } from 'react-native-svg';

import { useTheme } from '@/theme';

import { HUGE_ICONS, type HugeIconElement } from './hugeIcons.generated';

export type LineIconName = keyof typeof HUGE_ICONS;

/** The ramp in `sizes` (`iconXs`…`iconLg`); a number is a device-space box for the rare odd one. */
export type IconSize = 'xs' | 'sm' | 'md' | 'lg' | number;

export type IconProps = {
  name: LineIconName;
  /** Box size. Defaults to `sm`, the size beside body text. */
  size?: IconSize;
  /** A resolved colour (`colors.textMuted`), as the call sites already hold one. */
  color: string;
  /**
   * Hugeicons draws at 1.5 on its 24 grid. A caller's width is read on the old 2-based scale (the
   * tab bar thickens the active glyph to 2.4), so it is scaled by 0.75 to keep the same contrast.
   */
  strokeWidth?: number;
  /** Paints the glyph's closed shape too — a saved bookmark against an unsaved outline. */
  filled?: boolean;
  style?: StyleProp<ViewStyle>;
};

/**
 * The box that draws a line glyph as large as a filled glyph of `glyph` was drawn. Untitled UI
 * leaves a margin inside its 24 grid; a FontAwesome glyph filled its size. For the few sizes still
 * derived from a caller rather than taken off the ramp.
 */
export const lineBox = (glyph: number): number => glyph / 0.8;

/**
 * How much of the 24 grid a compact glyph spans, for sizing a box from a board's drawn glyph
 * length: `length / glyphSpan.arrow` draws an arrow exactly as long as the board's.
 */
export const glyphSpan = { chevron: 12 / 24, arrow: 14 / 24 } as const;

const BOX_KEY = { xs: 'iconXs', sm: 'iconSm', md: 'iconMd', lg: 'iconLg' } as const;

/**
 * One Hugeicons stroke-rounded glyph (the owner's pick, toreview §173), drawn with
 * react-native-svg from data generated by `scripts/gen-hugeicons.cjs`. Decorative by default: the
 * control around it carries the accessible label.
 */
export const Icon = memo(function Icon({
  name,
  size = 'sm',
  color,
  strokeWidth,
  filled = false,
  style,
}: IconProps) {
  const { sizes } = useTheme();
  const box = typeof size === 'number' ? size : sizes[BOX_KEY[size]];
  const width = strokeWidth != null ? strokeWidth * 0.75 : undefined;
  return (
    <Svg
      width={box}
      height={box}
      viewBox="0 0 24 24"
      fill="none"
      style={style}
      accessible={false}
      importantForAccessibility="no-hide-descendants"
    >
      {(HUGE_ICONS[name] as readonly HugeIconElement[]).map(([tag, attrs], index) => {
        const common = {
          stroke: color,
          fill: filled || attrs.solid ? color : 'none',
          strokeWidth: width ?? Number(attrs.strokeWidth ?? 1.5),
          strokeLinecap: (attrs.strokeLinecap as 'round' | undefined) ?? 'round',
          strokeLinejoin: (attrs.strokeLinejoin as 'round' | undefined) ?? 'round',
        };
        return tag === 'circle' ? (
          <Circle key={index} {...common} cx={String(attrs.cx)} cy={String(attrs.cy)} r={String(attrs.r)} />
        ) : (
          <Path
            key={index}
            {...common}
            d={String(attrs.d)}
            transform={attrs.transform ? String(attrs.transform) : undefined}
          />
        );
      })}
    </Svg>
  );
});
