import { webJobsFixture } from '@nextkin/shared/mock/fixtures/jobs.web';

import type { FixtureListing } from '../jobs/fixtureListing';

/**
 * The fixture provider's catalogue, read from the apps' board fixtures (ImBackendImplementationPlan
 * P11-01; toreview §105.18). One catalogue serves both apps: the web catalogue, which is the shared
 * seeds plus the web boards' additions. Times are kept relative (hours ago, hours to close) so the
 * listings stay fresh whenever the fixture provider serves them.
 *
 * Only listing facts cross over. Per-user and editorial fields (saved state, picks, seeded match
 * numbers, match reasons) are the server's to compute, and a company's "verified" badge is dropped:
 * V2 defines no verification. A job the user imported from a link is theirs, not a listing.
 */

const COUNTRY: [RegExp, string][] = [
  [/india|bengaluru|bangalore|chennai|hyderabad|mumbai|pune|delhi|gurugram|noida|kolkata/i, 'IN'],
  [/\b(ca|ny|wa|tx|ma|usa|united states)\b|san francisco|new york|seattle|austin|boston/i, 'US'],
  [/germany|berlin|munich|hamburg|deutschland/i, 'DE'],
  [/australia|sydney|melbourne|brisbane/i, 'AU'],
  [/london|united kingdom|\buk\b/i, 'GB'],
];

export const countryOf = (location: string): string => COUNTRY.find(([pattern]) => pattern.test(location))?.[1] ?? 'IN';

const hoursBetween = (from: number, to: number) => Math.round(((to - from) / 3_600_000) * 10) / 10;

export function fixtureCatalogue(now = Date.now()): FixtureListing[] {
  return webJobsFixture
    .filter((job) => !job.sourceUrl)
    .map((job) => ({
      id: job.id,
      title: job.title,
      company: job.company,
      ...(job.companyLogoUrl?.startsWith('asset:') ? { logoKey: job.companyLogoUrl.slice('asset:'.length) } : {}),
      location: job.location,
      country: countryOf(job.location),
      remote: job.remote,
      employmentType: job.employmentType,
      experienceLevel: job.experienceLevel,
      ...(job.experienceYears ? { experienceYears: job.experienceYears } : {}),
      ...(job.reference ? { reference: job.reference } : {}),
      ...(job.applicantsCount != null ? { applicantsCount: job.applicantsCount } : {}),
      ...(job.salary ? { salary: job.salary } : {}),
      postedAgoHours: hoursBetween(new Date(job.postedAt).getTime(), now),
      ...(job.closingAt ? { closingInHours: hoursBetween(now, new Date(job.closingAt).getTime()) } : {}),
      description: job.description,
      responsibilities: job.responsibilities,
      requirements: job.requirements,
      ...(job.benefits ? { benefits: job.benefits } : {}),
      ...(job.perks ? { perks: job.perks } : {}),
      ...(job.industries ? { industries: job.industries } : {}),
      tags: job.tags,
      companyIndustry: job.companyIndustry,
      companySize: job.companySize,
      companyWebsite: job.companyWebsite,
      ...(job.companyAbout ? { companyAbout: job.companyAbout } : {}),
      ...(job.companyFounded != null ? { companyFounded: job.companyFounded } : {}),
      ...(job.companyHeadquarters ? { companyHeadquarters: job.companyHeadquarters } : {}),
      ...(job.applyUrl ? { applyUrl: job.applyUrl } : {}),
    }));
}

/** The generated module's text: what `pnpm --filter @nextkin/server fixtures:jobs` writes. */
export function catalogueModule(listings: FixtureListing[]): string {
  return `// Generated by \`pnpm --filter @nextkin/server fixtures:jobs\` from the apps' board fixtures
// (src/seed/jobFixtures.ts). Do not edit by hand; test/jobFixtures.test.ts fails if it drifts.
import type { FixtureListing } from '../fixtureListing';

export const FIXTURE_CATALOGUE: readonly FixtureListing[] = ${JSON.stringify(listings, null, 2)};
`;
}
