import { sql } from 'kysely';
import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest';

import { groundedModel } from '../../evals/referenceModel';
import { createAiGateway } from '../../src/ai/gateway';
import { createFakeProvider } from '../../src/ai/providers/fake';
import { createAiSettings } from '../../src/ai/routing';
import { createDbTrace } from '../../src/ai/trace';
import { loadConfig } from '../../src/config';
import { createPdfRenderer } from '../../src/export/renderPdf';
import { createValkeyPublisher } from '../../src/pipeline/events';
import { dlqOf, QUEUES } from '../../src/queue/envelope';
import { createSqsQueue } from '../../src/queue/sqs';
import { buildStorage } from '../../src/storage/build';
import { buildWorker, type Worker } from '../../src/worker/build';
import { mobileLogin, registered, startHarness, type Harness } from './fixtures/authHarness';
import { log } from './fixtures/pipeline';

/**
 * P10-13's done-when, through the shared client both apps run: the library on the local backend.
 * A generated resume is listed, edited (If-Match), regenerated by section on the worker, confirmed,
 * exported to a real file behind a presigned URL, written from (a cover letter, an ATS check),
 * tailored on the mock from a copy, and deleted. Mock documents stay in the mock library.
 */
const config = loadConfig();
let h: Harness;
let worker: Worker;
const pdf = createPdfRenderer(config.CHROMIUM_PATH ? { executablePath: config.CHROMIUM_PATH } : {});
const queue = createSqsQueue({ region: config.AWS_REGION, endpoint: config.SQS_ENDPOINT, prefix: config.SQS_QUEUE_PREFIX });

beforeAll(async () => {
  h = await startHarness({ files: true });
  worker = buildWorker({
    db: h.db,
    queue,
    gateway: createAiGateway({ settings: createAiSettings(h.db, 0), providers: { resolve: (f) => (f === 'claude' ? createFakeProvider({ script: groundedModel }) : null), isDeveloperKey: () => false }, trace: createDbTrace(h.db, log), log, developer: 'test', dailyCapUsd: 0, retryDelayMs: () => 0 }),
    publisher: createValkeyPublisher(h.valkey),
    log,
    concurrency: 4,
    generationTimeoutSeconds: 180,
    scheduler: false,
    documents: { storage: buildStorage(config), exportsBucket: config.S3_BUCKET_EXPORTS, pdf },
  });
  worker.start();
});
afterAll(async () => {
  await worker.stop(1000);
  await pdf.close();
  queue.close();
  await h.close();
});
beforeEach(async () => {
  await h.db.withSystem('test: settle the outbox', (tx) => tx.updateTable('outbox').set({ published_at: sql`now()` }).where('published_at', 'is', null).execute());
  for (const name of [...QUEUES, ...QUEUES.map(dlqOf)]) await queue.purge!(name);
});

const JD = ['Senior Backend Engineer at Acme Payments', 'We build reliable payment services for merchants across Europe.', 'Requirements: strong Go and PostgreSQL skills, and experience running Kubernetes in production.', 'Nice to have: Terraform and Redis.'].join('\n');

describe('the library over the apps’ HTTP repositories (P10-13)', () => {
  it('lists, edits, regenerates, exports, writes from and deletes a server document', async () => {
    const { createRepos } = await import('@nextkin/shared/repos/create');
    const { createMockRepos, ExportBlockedError } = await import('@nextkin/shared/repos');
    const { createMockStore } = await import('@nextkin/shared/repos/state');
    const { adoptDocument } = await import('@nextkin/shared/repos/adopt');
    const { createHttpClient } = await import('@nextkin/shared/repos/http/client');

    const email = await registered(h);
    const tokens = await mobileLogin(h, email);
    const user = await h.db.withSystem('test: find the user', (tx) => tx.selectFrom('users').select('id').where('email', '=', email).executeTakeFirstOrThrow());
    await h.db.withUser({ userId: user.id, role: 'user' }, async (tx) => {
      const role = await tx
        .insertInto('experience')
        .values({ user_id: user.id, company: 'Lumen Pay', title: 'Senior Backend Engineer', start_date: '2020-03-01', is_current: true, responsibilities: ['Built the settlement service in Go, processing 2 million transactions daily', 'Moved 40 services onto Kubernetes with zero downtime'] })
        .returning('id')
        .executeTakeFirstOrThrow();
      for (const raw of ['Go', 'Kubernetes']) await tx.insertInto('experience_skills').values({ user_id: user.id, experience_id: role.id, raw_name: raw }).execute();
      for (const raw of ['Go', 'Kubernetes']) await tx.insertInto('profile_skills').values({ user_id: user.id, raw_name: raw }).execute();
    });

    let stored = { ...tokens, expiresIn: 3600 };
    const http = createHttpClient({
      baseUrl: 'http://localhost:3000',
      client: 'mobile',
      tokens: { get: async () => stored, set: async (next) => void (next && (stored = next)) },
      fetch: (input, init) => h.app.request(String(input), init) as Promise<Response>,
    });
    const store = createMockStore();
    const { repos } = createRepos(
      { sources: { jd: 'http', generations: 'http', resumes: 'http' }, http, uploader: async () => {}, adopt: (doc) => adoptDocument(store, doc) },
      createMockRepos(store),
    );
    const settle = (id: string) =>
      new Promise<{ status: string; resumeId?: string }>((resolve) => {
        const stop = repos.generations.subscribe(id, (g) => {
          if (g.status === 'ready' || g.status === 'failed') {
            stop();
            resolve(g);
          }
        });
      });

    const jd = await repos.jd.extract({ source: 'paste', text: JD });
    const started = await repos.generations.start({ kind: 'resume', jdId: jd.id, origin: 'build' });
    expect((await settle(started.id)).status).toBe('ready');
    const id = started.resumeId!;

    // The library lists the server document once, and none of the mock's example resumes beside
    // it (toreview §110.2: they duplicated the server's and could be picked to tailor).
    const list = await repos.resumes.list();
    expect(list.filter((r) => r.id === id)).toHaveLength(1);
    expect(list.filter((r) => !/^[0-9a-f-]{36}$/.test(r.id))).toEqual([]);

    // An edit is a new version (If-Match from the read), and the score moves with it.
    await repos.resumes.getContent(id);
    const edited = await repos.resumes.updateSection(id, 'summary', 'Backend engineer who runs payment systems end to end.');
    expect(edited.kind === 'resume' && edited.summary).toBe('Backend engineer who runs payment systems end to end.');
    expect((await repos.resumes.getVersions(id)).map((v) => v.version)).toEqual([2, 1]);

    // A section regenerates on the worker; the repository awaits it.
    const regenerated = await repos.resumes.regenerateSection(id, 'experience');
    expect(regenerated.kind === 'resume' && regenerated.summary).toBe('Backend engineer who runs payment systems end to end.');
    expect((await repos.resumes.getVersions(id))[0]!.changeNote).toBe('Regenerated Experience');

    // Export: confirm first (a typed error both apps handle), then a real file behind a link.
    await expect(repos.resumes.export(id, 'pdf')).rejects.toBeInstanceOf(ExportBlockedError);
    expect((await repos.resumes.confirmAccuracy(id)).accuracyConfirmed).toBe(true);
    const file = await repos.resumes.export(id, 'pdf');
    if (file.delivery !== 'file') throw new Error('expected a file');
    const downloaded = new Uint8Array(await (await fetch(file.url)).arrayBuffer());
    expect(Buffer.from(downloaded.subarray(0, 5)).toString('latin1')).toBe('%PDF-');
    expect(new Date(file.expiresAt).getTime() - Date.now()).toBeLessThanOrEqual(15 * 60_000);

    // A cover letter and an ATS check of a server document now run on the server.
    const letter = await repos.generations.start({ kind: 'cover_letter', sourceResumeId: id, jdId: jd.id, tone: 'concise' });
    expect(letter.id).toMatch(/^[0-9a-f-]{36}$/);
    const letterDone = await settle(letter.id);
    expect(letterDone.status).toBe('ready');
    const letterBody = await repos.resumes.getContent(letterDone.resumeId!);
    expect(letterBody).toMatchObject({ kind: 'cover_letter', tone: 'concise', resumeId: id });
    const check = await repos.generations.start({ kind: 'ats_check', sourceResumeId: id, jdId: jd.id });
    expect((await settle(check.id)).status).toBe('ready');

    // Tailoring from a server document stays on the mock, from a copy of it.
    const tailored = await repos.generations.start({ kind: 'resume', baseResumeId: id, jobId: 'job_stripe' });
    expect(tailored.id).not.toMatch(/^[0-9a-f-]{36}$/);
    expect(store.state.contents[id]).toBeDefined();

    // Delete is permanent.
    await repos.resumes.remove(id);
    expect((await repos.resumes.list()).some((r) => r.id === id)).toBe(false);
  }, 120_000);
});
